"""Declarative base and shared column helpers.

Conventions (PRD §10): UUIDv7 primary keys generated by the app, `timestamptz` set from the
injected Clock (no `now()` server defaults), money as `bigint` cents, enums as CHECK constraints.
"""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from datetime import datetime

from sqlalchemy import BigInteger, CheckConstraint, DateTime, ForeignKey, Integer, MetaData, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def uuid_pk() -> Mapped[uuid.UUID]:
    """Primary key; the value always comes from `app.ids.uuid7()`, never the database."""
    return mapped_column(UUID(as_uuid=True), primary_key=True)


def fk(target: str, *, nullable: bool = False, ondelete: str = "RESTRICT", index: bool = False) -> Mapped[uuid.UUID]:
    return mapped_column(UUID(as_uuid=True), ForeignKey(target, ondelete=ondelete), nullable=nullable, index=index)


def ts(*, nullable: bool = False) -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), nullable=nullable)


def cents(*, nullable: bool = False, default: int | None = None) -> Mapped[int]:
    return mapped_column(
        BigInteger,
        nullable=nullable,
        server_default=None if default is None else text(str(default)),
    )


def version_col() -> Mapped[int]:
    """Optimistic-concurrency version (PRD §21.2); starts at 1, bumped on every change."""
    return mapped_column(Integer, nullable=False, server_default=text("1"))


def enum_check(
    column: str, values: Sequence[str], *, name: str | None = None, nullable: bool = False
) -> CheckConstraint:
    allowed = ", ".join(f"'{v}'" for v in values)
    expr = f"{column} IN ({allowed})"
    if nullable:
        expr = f"{column} IS NULL OR {expr}"
    return CheckConstraint(expr, name=name or f"{column}_enum")


def exactly_one_participant() -> CheckConstraint:
    """A member-or-guest reference is two nullable FKs with exactly one set (ADR-0003)."""
    return CheckConstraint("num_nonnulls(member_id, guest_id) = 1", name="exactly_one_participant")
